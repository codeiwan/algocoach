from enum import StrEnum
from typing import Self

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    field_validator,
    model_validator,
)

from app.schemas.agent import ProgrammingLanguage


class ReviewStatus(StrEnum):
    """Outcome of an AI-only pre-submission review."""

    RISK_FOUND = "RISK_FOUND"
    NO_OBVIOUS_RISK = "NO_OBVIOUS_RISK"
    UNCERTAIN = "UNCERTAIN"


class ReviewCategory(StrEnum):
    """Categories of potential submission problems."""

    LOGIC = "LOGIC"
    EDGE_CASE = "EDGE_CASE"
    COMPLEXITY = "COMPLEXITY"
    INPUT_OUTPUT = "INPUT_OUTPUT"
    CONSTRAINT = "CONSTRAINT"
    LANGUAGE = "LANGUAGE"


class ReviewSeverity(StrEnum):
    """Importance of an identified review finding."""

    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"


class SubmissionReviewRequest(BaseModel):
    """Code and problem context submitted for static review."""

    model_config = ConfigDict(extra="forbid")

    session_id: str = Field(
        min_length=1,
        max_length=128,
    )

    code_revision: int = Field(ge=0)

    problem_text: str = Field(
        min_length=1,
        max_length=20_000,
    )

    current_code: str = Field(
        min_length=1,
        max_length=40_000,
    )

    language: ProgrammingLanguage

    @field_validator(
        "session_id",
        "problem_text",
        "current_code",
    )
    @classmethod
    def reject_blank_text(cls, value: str) -> str:
        """Reject whitespace-only values without altering source text."""

        if not value.strip():
            raise ValueError("Value must not be blank.")

        return value


class ReviewFinding(BaseModel):
    """A potential issue supported by concrete source evidence."""

    model_config = ConfigDict(extra="forbid")

    category: ReviewCategory
    severity: ReviewSeverity

    description: str = Field(
        min_length=1,
        max_length=1500,
    )

    evidence: str = Field(
        min_length=1,
        max_length=1500,
    )

    line_start: int | None = Field(
        default=None,
        ge=1,
    )

    line_end: int | None = Field(
        default=None,
        ge=1,
    )

    @field_validator("description", "evidence")
    @classmethod
    def reject_blank_finding(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("Finding text must not be blank.")

        return value

    @model_validator(mode="after")
    def validate_line_range(self) -> Self:
        """Line locations must be complete and ordered."""

        start = self.line_start
        end = self.line_end

        if (start is None) != (end is None):
            raise ValueError(
                "line_start and line_end must both be set or both be null."
            )

        if start is not None and end is not None and start > end:
            raise ValueError(
                "line_start must not exceed line_end."
            )

        return self


class SubmissionReviewResult(BaseModel):
    """Validated outcome of a pre-submission AI review."""

    model_config = ConfigDict(extra="forbid")

    # Assigned by the backend, not generated by the LLM.
    reviewed_revision: int = Field(ge=0)

    status: ReviewStatus

    summary: str = Field(
        min_length=1,
        max_length=2000,
    )

    findings: list[ReviewFinding] = Field(
        default_factory=list,
        max_length=5,
    )

    complexity_assessment: str | None = Field(
        default=None,
        max_length=1000,
    )

    suggested_checks: list[str] = Field(
        default_factory=list,
        max_length=5,
    )

    @field_validator("summary")
    @classmethod
    def reject_blank_summary(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("Review summary must not be blank.")

        return value

    @field_validator("suggested_checks")
    @classmethod
    def reject_blank_checks(cls, values: list[str]) -> list[str]:
        if any(not value.strip() for value in values):
            raise ValueError("Suggested checks must not be blank.")

        return values

    @model_validator(mode="after")
    def validate_status_consistency(self) -> Self:
        """Ensure the overall status agrees with the findings."""

        if (
            self.status == ReviewStatus.RISK_FOUND
            and not self.findings
        ):
            raise ValueError(
                "RISK_FOUND requires at least one finding."
            )

        if (
            self.status == ReviewStatus.NO_OBVIOUS_RISK
            and self.findings
        ):
            raise ValueError(
                "NO_OBVIOUS_RISK must not contain risk findings."
            )

        return self
